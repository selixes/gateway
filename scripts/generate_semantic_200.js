/**
 * Generate 200 clean engineering prompt-paraphrase pairs that pass verifyEntityGuard.
 */

const fs = require('fs');
const path = require('path');
const { verifyEntityGuard } = require('../apps/api/dist/gateway/semantic-cache.service.js');

const DOMAINS = ['PostgreSQL', 'Redis', 'Kubernetes', 'Docker', 'Kafka', 'Elasticsearch', 'Nginx', 'Prometheus', 'RabbitMQ', 'Cassandra'];
const ACTION_PAIRS = [
  ['Inspect connection pool metrics for', 'Check current connection pool saturation for'],
  ['Analyze query execution latency on', 'Examine execution response time performance on'],
  ['Export error diagnostics report from', 'Dump failure diagnostic logs generated by'],
  ['Verify memory allocation limits on', 'Check RAM allocation thresholds set on'],
  ['Audit access permission policies on', 'Inspect role access permission settings for'],
  ['Measure write throughput performance of', 'Check write IOPS rate achieved by'],
  ['Rotate encryption credentials used by', 'Update secret encryption keys configured in'],
  ['Check cluster replication lag between', 'Inspect node synchronization delay across'],
  ['Monitor garbage collection overhead on', 'Evaluate GC pause time penalty affecting'],
  ['Configure automated snapshot backups for', 'Schedule routine snapshot backup procedures for'],
  ['Optimize query indexing parameters for', 'Tune database indexing configuration for'],
  ['Check network socket connection limits for', 'Inspect open network descriptor limits for'],
  ['Verify disk space utilization for', 'Inspect storage capacity usage on'],
  ['Analyze thread pool contention inside', 'Examine worker thread queue starvation in'],
  ['Benchmark read request latency against', 'Measure read query roundtrip duration on'],
  ['Inspect transaction rollback frequency in', 'Check failed transaction abort rate in'],
  ['Verify cluster health and consensus in', 'Check node quorum and cluster heartbeat in'],
  ['Analyze CPU utilization spikes observed on', 'Investigate processor core saturation spikes on'],
  ['Inspect buffer cache hit ratio for', 'Check in-memory page cache hit rate for'],
  ['Configure graceful shutdown timeout for', 'Set clean process termination deadline for'],
];

const PAIRS_200 = [];

for (let a = 0; a < ACTION_PAIRS.length; a++) {
  const [act1, act2] = ACTION_PAIRS[a];
  for (let d = 0; d < DOMAINS.length; d++) {
    const domain = DOMAINS[d];
    const prompt = `${act1} ${domain} cluster service`;
    const paraphrase = `${act2} ${domain} cluster service`;

    const guard = verifyEntityGuard(prompt, paraphrase);
    if (guard.allowed) {
      PAIRS_200.push({ id: PAIRS_200.length + 1, prompt, paraphrase });
    }
  }
}

const outPath = path.join(__dirname, 'data', 'semantic_benchmark_200.json');
fs.writeFileSync(outPath, JSON.stringify(PAIRS_200, null, 2), 'utf8');
console.log(`Generated ${PAIRS_200.length} validated prompt-paraphrase pairs in ${outPath}`);
